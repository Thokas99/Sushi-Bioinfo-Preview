import assert from 'node:assert/strict';
import fs from 'node:fs';
import {formatFromName, genomicPreview} from '../src/format-core.js';
import {LIMITS, prepareTable, sortRows, guessTypes} from '../src/table-core.js';
assert.equal(formatFromName('data.bed'), 'bed');
const vcf = '##fileformat=VCFv4.3\n##source=foo\n#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\nchr1\t42\t.\tA\tC\t40\tPASS\tDP=20\tGT\t0/1\n';
let out = genomicPreview('x.vcf', vcf, false);
assert.deepEqual(out.headers.slice(0,3), ['CHROM','POS','ID']);
assert.equal(out.rows.length, 1);
assert.match(out.notes.join(';'), /1 sample columns/);
assert.match(out.notes.join(';'), /1-based/);
assert.equal(genomicPreview('x.vcf', vcf.slice(0,-4), true).rows.length, 0); // drop incomplete last line
out = genomicPreview('x.bed', 'track name=peaks\nchr1\t100\t200\nchr2\t200\t210\tpeak2\n', false);
assert.equal(out.rows.length, 2);
assert.equal(out.headers.length, 4);
assert.equal(out.headers[1], 'chromStart');
assert.match(out.notes.join(';'), /0-based/);
const clippedBed = genomicPreview('clipped.bed', `chr1\t1\t2\t${'x'.repeat(600)}\n`, false);
assert.deepEqual(clippedBed.truncatedFields.get(0), [3]);
assert.equal(clippedBed.clippedFields, true);
const partialBed = genomicPreview('partial.bed', 'chr1\t1\t2\nchr2\t2\tunfinished', true);
assert.equal(partialBed.rows.length, 1);
assert.equal(partialBed.incompleteRecord, true);
assert.equal(partialBed.truncatedRows, false);
assert.equal(partialBed.truncatedBytes, true);
out = genomicPreview('x.mtx', '%%MatrixMarket matrix coordinate integer general\n%test\n3 5 2\n1 2 6\n3 1 12\n', false);
assert.equal(out.rows.length, 2);
assert.deepEqual(out.rows[1], ['3','1','12']);
assert.match(out.notes.join(';'), /3 × 5, 2/);
out = genomicPreview('complex.mtx', '%%MatrixMarket matrix coordinate complex general\n2 3 1\n1 2 1.5 -2.25\n', false);
assert.deepEqual(out.headers, ['row','column','real','imaginary']);
assert.deepEqual(out.rows, [['1','2','1.5','-2.25']]);
out = genomicPreview('pattern.mtx', '%%MatrixMarket matrix coordinate pattern symmetric\n2 2 1\n1 2\n', false);
assert.deepEqual(out.headers, ['row','column']);
assert.deepEqual(out.rows, [['1','2']]);
out = genomicPreview('array.mtx', '%%MatrixMarket matrix array complex general\n1 2\n1.5 -2\n0.25 4\n', false);
assert.equal(out.kind, 'Matrix Market array');
assert.deepEqual(out.headers, ['real','imaginary']);
assert.deepEqual(out.rows, [['1.5','-2'],['0.25','4']]);
assert.match(out.notes.join(';'), /Dense array values are shown in storage order/);
out = genomicPreview('invalid.mtx', '%%MatrixMarket matrix coordinate integer general\n1 2 3 4 5 6 7\n', false);
assert.match(out.notes.join(';'), /dimensions unavailable/);
out = genomicPreview('x.gtf', '# note\nchr1\tStringTie\texon\t2\t4\t.\t+\t.\tgene_id "G";\n', false);
assert.equal(out.rows.length,1);
assert.equal(out.headers.length,9);
assert.match(out.notes.join(';'), /1-based inclusive/);
const exampleGff = genomicPreview('example.gff3', fs.readFileSync(new URL('../examples/example.gff3', import.meta.url), 'utf8'), false);
assert.equal(exampleGff.rows.length, 4);
assert.ok(exampleGff.rows.every(row => row.length === 9));
const exampleMtx = genomicPreview('example.mtx', fs.readFileSync(new URL('../examples/example.mtx', import.meta.url), 'utf8'), false);
assert.equal(exampleMtx.rows.length, 6);
assert.match(exampleMtx.notes.join(';'), /4 × 5, 6/);
assert.deepEqual([LIMITS.bytes,LIMITS.rows,LIMITS.tableRows,LIMITS.columns,LIMITS.cells,LIMITS.fieldChars],
    [64*1024*1024,25000,5000,256,1_280_000,512]);
const big = 'col1\tcol2\n' + 'sample\t42\n'.repeat(LIMITS.rows + 200);
const parsed = prepareTable(big, '\t');
assert.equal(parsed.rows.length, LIMITS.rows);
assert.equal(parsed.truncatedRows, true);
const sorted = sortRows(parsed.rows, 1, true, guessTypes(parsed.rows,2));
assert.equal(sorted.length, LIMITS.rows);
const preview = genomicPreview('many.bed', 'chr1\t1\t2\n'.repeat(LIMITS.rows + 100), false);
assert.equal(preview.rows.length,LIMITS.tableRows);
assert.equal(preview.rowLimit,true);
assert.ok(preview.rows.every(row=>row.length===3));
console.log('Format detection, genomics parsing and safety caps passed.');

// Genomic files and general tabular files must use the same limits.
const wideHeaders = Array.from({length: 300}, (_, i) => `sample_${i}`).join('\t');
const wideBed = `chr1\t1\t2\t${wideHeaders}\n`;
const wide = genomicPreview('wide.bed', wideBed, false);
assert.equal(wide.headers.length, LIMITS.columns);
assert.equal(wide.colLimit, true);
// Many tiny lines must not be eagerly split into millions of strings.
const tiny = 'chr1\t1\t2\n'.repeat(LIMITS.rows + 20000);
assert.equal(genomicPreview('tiny.bed', tiny, false).rows.length, LIMITS.tableRows);
